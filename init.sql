CREATE DATABASE IF NOT EXISTS library;

USE library;

CREATE TABLE IF NOT EXISTS employees (
 employee_id INT8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
 name STRING NOT NULL,
 last_name STRING NOT NULL,
 position STRING NOT NULL,
 boss_id INT8 NULL,
 salary INT8 NOT NULL,
 employment_date DATE NOT NULL,
 phone_number STRING NOT NULL,
 address STRING NOT NULL,
 email STRING NOT NULL,
 CONSTRAINT fk_employees_boss FOREIGN KEY (boss_id) REFERENCES employees (employee_id)
);

CREATE TABLE IF NOT EXISTS readers (
 reader_id INT8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
 name STRING NOT NULL,
 last_name STRING NOT NULL,
 birth_date DATE NOT NULL,
 phone_number STRING NOT NULL,
 address STRING NOT NULL,
 email STRING NULL
);

CREATE TABLE IF NOT EXISTS accounts (
reader_id INT8 NULL,
username STRING NOT NULL,
password STRING NOT NULL,
CONSTRAINT fk_accounts_reader FOREIGN KEY (reader_id) REFERENCES readers (reader_id)
);

CREATE TABLE IF NOT EXISTS authors (
 author_id INT8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
 name STRING NOT NULL,
 last_name STRING NOT NULL,
 birth_date DATE NOT NULL,
 nationality STRING NOT NULL
);

CREATE TABLE IF NOT EXISTS books (
 book_id INT8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
 title STRING NOT NULL,
 publisher STRING NOT NULL,
 release_date DATE NOT NULL,
 language STRING NOT NULL,
 available BOOLEAN NOT NULL,
 reader_id INT8 NULL,
 price DECIMAL(5, 2) NOT NULL,
CONSTRAINT fk_books_reader FOREIGN KEY (reader_id) REFERENCES readers (reader_id)
);

CREATE TABLE IF NOT EXISTS books_authors (
 book_id INT8 NOT NULL,
 author_id INT8 NOT NULL,
 CONSTRAINT fk_books_authors_book FOREIGN KEY (book_id) REFERENCES books (book_id),
CONSTRAINT fk_books_authors_author FOREIGN KEY (author_id) REFERENCES authors (author_id)
);

CREATE TABLE IF NOT EXISTS reviews (
 review_id INT8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
 book_id INT8 NOT NULL,
 reader_id INT8 NOT NULL,
 rating INT8 NOT NULL,
 review TEXT NOT NULL,
 CONSTRAINT fk_reviews_reader FOREIGN KEY (reader_id) REFERENCES readers (reader_id),
CONSTRAINT fk_reviews_book FOREIGN KEY (book_id) REFERENCES books (book_id)
);

